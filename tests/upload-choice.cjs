// Диалог «Загрузить новую ведомость»: три действия; тёплая тема «Дизайн 1».
const {JSDOM}=require('jsdom');
const fs=require('node:fs'),assert=require('node:assert/strict');
const tick=()=>new Promise(r=>setTimeout(r,35));
(async()=>{
 const dom=new JSDOM(fs.readFileSync('internal/server/web/index.html','utf8'),{url:'http://app.test',runScripts:'outside-only',pretendToBeVisual:true});
 const w=dom.window,d=w.document;
 w.scrollTo=()=>{};w.setInterval=()=>1;
 w.fetch=async()=>({ok:true,json:async()=>({hasWorkbook:false})});
 w.eval(fs.readFileSync('internal/server/web/app.js','utf8'));
 await tick();
 let workbookPickers=0,etalonPickers=0;
 d.getElementById('fileInput').click=()=>{workbookPickers++;};
 d.getElementById('etalonFileInput').click=()=>{etalonPickers++;};
 const modal=d.getElementById('uploadChoiceModal');
 assert.ok(modal,'Upload choice modal exists in markup');
 assert.ok(modal.classList.contains('hidden'),'Hidden by default');
 d.getElementById('btnUpload').click();await tick();
 assert.ok(!modal.classList.contains('hidden'),'Opens from Загрузить новую ведомость');
 assert.deepEqual([...modal.querySelectorAll('.v4-modal-toolbar button')].map(b=>b.textContent.trim()),['Загрузить ведомость','Загрузить эталон','Отмена'],'Three actions');
 assert.equal(d.activeElement&&d.activeElement.id,'btnPickWorkbookFile','Focus moves to the primary action');
 d.getElementById('btnPickWorkbookFile').click();
 assert.ok(modal.classList.contains('hidden'),'Choice closes');
 assert.equal(workbookPickers,1,'Workbook picker opens');
 d.getElementById('btnUpload').click();await tick();
 d.getElementById('btnPickEtalonFile').click();
 assert.ok(modal.classList.contains('hidden'),'Choice closes for etalon');
 assert.equal(etalonPickers,1,'Etalon picker opens');
 d.getElementById('btnUpload').click();await tick();
 d.getElementById('btnCancelUploadChoice').click();
 assert.ok(modal.classList.contains('hidden'),'Отмена returns to the main menu');
 assert.equal(workbookPickers,1);assert.equal(etalonPickers,1);
 d.getElementById('btnUpload').click();await tick();
 modal.dispatchEvent(new w.Event('click'));
 assert.ok(modal.classList.contains('hidden'),'Backdrop click closes');
 d.getElementById('btnUpload').click();await tick();
 d.getElementById('btnCloseUploadChoice').click();
 assert.ok(modal.classList.contains('hidden'),'✕ closes');
 d.getElementById('btnUpload').click();await tick();
 modal.dispatchEvent(new w.KeyboardEvent('keydown',{key:'Escape',bubbles:true}));
 assert.ok(modal.classList.contains('hidden'),'Escape closes');
 assert.equal(workbookPickers,1);assert.equal(etalonPickers,1,'Neither picker ever opened without an explicit action');
 // Тёплая тема «Дизайн 1» — только переменные; тёмная тема и таблицы не тронуты.
 const css=fs.readFileSync('internal/server/web/styles.css','utf8');
 assert.match(css,/--bg: #f6f1e7;/,'Warm paper background');
 assert.match(css,/--surface: #fffdf8;/,'Warm surface');
 assert.match(css,/--border: #e5dac3;/,'Warm borders');
 assert.match(css,/--primary: #b45309;/,'Warm accent');
 assert.match(css,/--radius: 12px;/,'Softer corners');
 assert.match(css,/\[data-theme="dark"\]/,'Dark theme untouched');
 console.log('Upload choice dialog and warm theme tests passed');
})().catch(e=>{console.error(e);process.exitCode=1;});
